// Keep editable English JSON content as the source; generate lazy Lingui bindings.
import fs from 'node:fs'
import path from 'node:path'
import prettier from 'prettier'
const formatting = JSON.parse(fs.readFileSync('.prettierrc', 'utf8'))
const format = (text) =>
  prettier.format(text, { ...formatting, parser: 'typescript' })
const oldBindings = new Map()
if (fs.existsSync('src/i18n/content.ts')) {
  const previous = fs.readFileSync('src/i18n/content.ts', 'utf8')
  for (const match of previous.matchAll(
    /import content(\d+) from ['"]\.\.\/\.\.\/([^'"]+)['"]/g
  ))
    oldBindings.set('localized' + match[1], match[2])
}
const exportName = (file) =>
  'content' +
  file
    .replace(/^content\//, '')
    .replace(/\.json$/, '')
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((token) => token[0].toUpperCase() + token.slice(1))
    .join('')

const display =
  /^(title|titleMuted|subtitle|description|desc|text|help|placeholder|label|info|note|announcement|devPreviewAnnouncement|siteTitle|siteTagline|siteDescription|siteImageAlt|taglineContinuation|copyright|searchPlaceholder|contactLabel|languageLabel|languageHelp|updated|ctd|close|save|accept|reject|configure|manageIntro|analyticsText|button.*|.*Title|.*Description|.*Help|.*Label|.*Text|success|error|loading|pending|successAction|errorAction|action|message|intro|disclaimer)$/
const messages = new Set()
const files = []
function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(file)
    else if (
      entry.name.endsWith('.json') &&
      !/networks-metadata|repo-metadata/.test(file)
    )
      files.push(file)
  }
}
walk('content')
files.push('src/components/@shared/PolicyEditor/editor.json')
fs.mkdirSync('src/i18n', { recursive: true })
const imports = []
const bindings = []
for (const [index, file] of files.entries()) {
  const paths = []
  function visit(value, parts = [], parent) {
    if (value && typeof value === 'object') {
      for (const [key, child] of Object.entries(value))
        visit(child, [...parts, key], value)
    } else if (
      typeof value === 'string' &&
      value &&
      !/^(https?:|\/|did:|0x)/.test(value)
    ) {
      const key = parts.at(-1),
        group = parts.at(-2)
      if (!/[a-zA-Z]/.test(value) || /[{}]/.test(value)) return
      const isName =
        key === 'name' &&
        !parent.type &&
        !parent.required &&
        !parent.placeholder &&
        !parent.help
      if (
        display.test(key) ||
        isName ||
        group === 'points' ||
        group === 'prefixes' ||
        group === 'postfixes' ||
        (group === 'options' && /[A-Z\s]/.test(value)) ||
        (!/^(name|type|value|link|url|href|src|logo|logoColor|icon|scene|visual|language|direction|date|dateFormat|policy|default|action|actions|disclaimerValues)$/.test(
          key
        ) &&
          !/^\d+$/.test(key))
      ) {
        messages.add(value)
        // Option values are data. Translate their visible labels in the form renderer.
        if (
          group !== 'options' &&
          !['URL', 'S3', 'IPFS', 'Arweave', 'FTP/FTPS', 'EDC', 'REA'].includes(
            value
          )
        )
          paths.push(parts.join('.'))
      }
    }
  }
  visit(JSON.parse(fs.readFileSync(file, 'utf8')))
  const name = 'content' + index
  imports.push(`import ${name} from '../../${file}'`)
  bindings.push(
    `export const ${exportName(
      file
    )} = localizeContent(${name}, ${JSON.stringify(paths)})`
  )
}
fs.writeFileSync(
  'src/i18n/content.ts',
  format(
    `// Generated by scripts/i18n/content.mjs. Edit content/*.json instead.\nimport { localizeContent } from './localizeContent'\n${imports.join(
      '\n'
    )}\n${bindings.join('\n')}\n`
  )
)
fs.writeFileSync(
  'src/i18n/contentMessages.ts',
  format(
    `// Generated message descriptors for JSON content.\nexport const contentMessages = [\n${[
      ...messages
    ]
      .sort()
      .map((id) => `  /* i18n */ { id: ${JSON.stringify(id)} }`)
      .join(',\n')}\n]\n`
  )
)
// Rewrite original content imports, including imports already migrated by this script.
function migrate(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, e.name)
    if (e.isDirectory()) {
      if (!['i18n', 'locales'].includes(e.name)) migrate(file)
    } else if (
      /\.tsx?$/.test(file) &&
      !file.endsWith('/Seo/DocumentHead.tsx')
    ) {
      let s = fs.readFileSync(file, 'utf8')
      s = s.replace(
        /import (\w+) from ['"]([^'"]*(?:content\/[^'"]+|editor)\.json)['"]/g,
        (full, name, source) => {
          const target = path.normalize(path.join(path.dirname(file), source))
          const index = files.indexOf(target)
          return index < 0
            ? full
            : `import { ${exportName(target)} as ${name} } from '${path
                .relative(path.dirname(file), 'src/i18n/content')
                .replaceAll('\\', '/')
                .replace(/^(?!\.)/, './')}'`
        }
      )
      for (const sourceFile of files) {
        const previousName =
          'content_' +
          sourceFile.replace(/\.json$/, '').replaceAll(/[^a-zA-Z0-9]/g, '_')
        s = s.replaceAll(previousName + ' as ', exportName(sourceFile) + ' as ')
      }
      s = s.replace(/\b(localized\d+) as /g, (full, binding) =>
        oldBindings.has(binding)
          ? exportName(oldBindings.get(binding)) + ' as '
          : full
      )
      if (s !== fs.readFileSync(file, 'utf8')) fs.writeFileSync(file, format(s))
    }
  }
}
migrate('src')
console.log(
  `Registered ${messages.size} content messages from ${files.length} files`
)
